#!/usr/bin/env node
// Sync builtin extension frontends into the app source tree (plan 04, ServerKit decision D5).
//
//   node scripts/sync-builtin-frontends.mjs           # write the synced copies
//   node scripts/sync-builtin-frontends.mjs --check    # CI drift gate: exit 1 if out of date
//
// SOURCE OF TRUTH: `builtin-extensions/<slug>/frontend/`. Those files are authored alongside
// the extension's backend and manifest. This script copies them verbatim into
// `frontend/src/extensions/<slug>/`, which Vite's build-time glob imports (third-party
// extensions ship backend only, so only builtins have compiled-in frontends). The copies are
// tracked so the app builds without a codegen step, and `--check` in CI proves they never
// drift from the source.
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, '..')
const BUILTINS_DIR = path.join(REPO_ROOT, 'builtin-extensions')
const DEST_ROOT = path.join(REPO_ROOT, 'frontend', 'src', 'extensions')

const check = process.argv.includes('--check')

const GENERATED_BANNER =
  '// @generated by scripts/sync-builtin-frontends.mjs — DO NOT EDIT.\n' +
  '// Source of truth: builtin-extensions/<slug>/frontend/. Run the sync script to update.\n'

async function exists(p) {
  try {
    await fs.access(p)
    return true
  } catch {
    return false
  }
}

/** Recursively list files (relative paths) under a directory. */
async function listFiles(dir, base = dir) {
  const out = []
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...(await listFiles(abs, base)))
    else out.push(path.relative(base, abs).split(path.sep).join('/'))
  }
  return out
}

/** For a `.jsx`/`.js` file, prepend the generated banner; copy others verbatim. */
async function renderContent(srcPath, rel) {
  const raw = await fs.readFile(srcPath)
  if (/\.(jsx?|tsx?)$/.test(rel)) {
    return Buffer.from(GENERATED_BANNER + raw.toString('utf8'), 'utf8')
  }
  return raw
}

async function discoverBuiltins() {
  if (!(await exists(BUILTINS_DIR))) return []
  const slugs = []
  for (const entry of await fs.readdir(BUILTINS_DIR, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    if (await exists(path.join(BUILTINS_DIR, entry.name, 'frontend'))) slugs.push(entry.name)
  }
  return slugs.sort()
}

async function main() {
  const slugs = await discoverBuiltins()
  const drift = []
  let written = 0

  for (const slug of slugs) {
    const srcDir = path.join(BUILTINS_DIR, slug, 'frontend')
    const destDir = path.join(DEST_ROOT, slug)
    const relFiles = await listFiles(srcDir)

    // Detect stale files in the dest that no longer exist in the source.
    if (await exists(destDir)) {
      for (const existing of await listFiles(destDir)) {
        if (!relFiles.includes(existing)) {
          drift.push(`stale: ${slug}/${existing} (removed from source)`)
          if (!check) await fs.rm(path.join(destDir, existing))
        }
      }
    }

    for (const rel of relFiles) {
      const content = await renderContent(path.join(srcDir, rel), rel)
      const destPath = path.join(destDir, rel)
      const current = (await exists(destPath)) ? await fs.readFile(destPath) : null
      if (current && current.equals(content)) continue
      drift.push(`out-of-date: ${slug}/${rel}`)
      if (!check) {
        await fs.mkdir(path.dirname(destPath), { recursive: true })
        await fs.writeFile(destPath, content)
        written++
      }
    }
  }

  if (check) {
    if (drift.length) {
      console.error('Builtin frontend drift detected — run `node scripts/sync-builtin-frontends.mjs`:')
      for (const d of drift) console.error('  ' + d)
      process.exit(1)
    }
    console.log(`OK — ${slugs.length} builtin frontend(s) in sync.`)
  } else {
    console.log(
      written
        ? `Synced ${written} file(s) across ${slugs.length} builtin frontend(s).`
        : `Already in sync — ${slugs.length} builtin frontend(s).`
    )
  }
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
